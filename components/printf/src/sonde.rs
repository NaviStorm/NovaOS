//! Byte-for-byte comparison in EL0/Ring 3, including streams larger than the heap.
use super::*;
use nova_cli::runtime as rt;
fn take<'a>(data: &mut &'a [u8], n: usize) -> &'a [u8] {
    let (first, rest) = data.split_at(n);
    *data = rest;
    first
}
fn u32le(data: &mut &[u8]) -> usize {
    u32::from_le_bytes(take(data, 4).try_into().unwrap()) as usize
}
struct Expected<'a> {
    runs: bool,
    data: &'a [u8],
    byte: u8,
    count: usize,
}
impl<'a> Expected<'a> {
    fn read(data: &mut &'a [u8]) -> Self {
        let runs = take(data, 1)[0] != 0;
        let n = u32le(data);
        Self {
            runs,
            data: take(data, n),
            byte: 0,
            count: 0,
        }
    }
    fn accept(&mut self, mut bytes: &[u8]) -> bool {
        if !self.runs {
            if !self.data.starts_with(bytes) {
                return false;
            }
            self.data = &self.data[bytes.len()..];
            return true;
        }
        while !bytes.is_empty() {
            if self.count == 0 {
                if self.data.len() < 5 {
                    return false;
                }
                self.byte = take(&mut self.data, 1)[0];
                self.count = u32le(&mut self.data)
            }
            let n = self.count.min(bytes.len());
            if bytes[..n].iter().any(|&b| b != self.byte) {
                return false;
            }
            self.count -= n;
            bytes = &bytes[n..]
        }
        true
    }
}
struct Monitor<'a> {
    streams: [Expected<'a>; 2],
    valid: bool,
}
impl Output for Monitor<'_> {
    fn write(&mut self, err: bool, bytes: &[u8]) -> Result<(), ()> {
        self.valid &= self.streams[err as usize].accept(bytes);
        Ok(())
    }
}
fn log(s: &str) {
    rt::call(rt::DEBUG_WRITE, s.as_ptr() as u64, s.len() as u64, 0);
}
// Match the Darwin corpus and discard the generated bytes after observing
// each slice. The differential run validates these four corpora separately.
fn benchmark(mode: u64) -> ! {
    struct Sink;
    impl Output for Sink {
        fn write(&mut self, err: bool, b: &[u8]) -> Result<(), ()> {
            core::hint::black_box(b);
            if err { Err(()) } else { Ok(()) }
        }
    }
    let (fmt, arg, count): (&[u8], &[u8], usize) = match mode {
        1 => (b"%s", b"x", 1),
        2 => (
            b"%s\n",
            b"NNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNN",
            30,
        ),
        3 => (b"%b", br"\0\xffA\0\xffA\0\xffA\0\xffA\0\xffA\0\xffA", 30),
        4 => (b"%+.9g\n", b"98765.125", 30),
        _ => rt::exit(2),
    };
    let mut args = alloc::vec![arg;count+1];
    args[0] = fmt;
    for _ in 0..128 {
        let status = engine::run(&mut Sink, core::hint::black_box(&args), Locale::default());
        if status != 0 {
            rt::exit(1)
        }
    }
    rt::exit(0)
}
#[unsafe(no_mangle)]
extern "C" fn run() -> ! {
    if rt::config(0) != 0 {
        benchmark(rt::config(0))
    }
    let mut data = include_bytes!(env!("PRINTF_VECTORS")).as_slice();
    let mut tests = 0;
    let mut errors = 0;
    while !data.is_empty() {
        let header = take(&mut data, 4);
        let id = header[0];
        let mut argv = Vec::new();
        for _ in 0..header[2] {
            let n = u16::from_le_bytes(take(&mut data, 2).try_into().unwrap());
            argv.push(take(&mut data, n.into()));
        }
        let mut monitor = Monitor {
            streams: [Expected::read(&mut data), Expected::read(&mut data)],
            valid: true,
        };
        let mut locale = Locale {
            posix: header[1] != 0,
            ..Locale::default()
        };
        if id != 0 {
            locale.decode = utf8;
            locale.encode = encode_utf8;
            locale.curved_quotes = true;
            locale.groups = &[3];
            locale.french = id == 2;
            locale.decimal = if id == 2 { b"," } else { b"." };
            locale.separator = if id == 2 { " ".as_bytes() } else { b"," };
        }
        let code = engine::run(&mut monitor, &argv, locale);
        if code != header[3]
            || !monitor.valid
            || monitor
                .streams
                .iter()
                .any(|s| !s.data.is_empty() || s.count != 0)
        {
            errors += 1;
            if errors <= 12 {
                log(&alloc::format!("PRINTF ECART {tests} statut {code}"))
            }
        }
        tests += 1;
    }
    log(&alloc::format!("PRINTF MOTEUR cas={tests} ecarts={errors}"));
    rt::exit(u64::from(errors != 0))
}
